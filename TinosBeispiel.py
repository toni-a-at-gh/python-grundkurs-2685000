#!/usr/bin/env python3

# Definition der Funktionen:
def Subtrahieren(op1: int, op2: int) -> int:
    """Subtraktion von zwei Operatoren"""
    return op1 - op2


def Addieren(op1: int, op2: int) -> int:
    """Addition von zwei Operatoren"""
    return op1 + op2


def Multiplizieren(op1: int, op2: int) -> int:
    """Multiplikation von zwei Opertoren"""
    return op1 * op2


def Dividieren(op1: int, op2: int) -> int:
    """Dividieren von zwei Operatoren"""
    return op1 / op2


